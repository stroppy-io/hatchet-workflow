#!/usr/bin/env python3
"""Merge openapi/parts/*.yaml into openapi/openapi.yaml.

Parts are plain OpenAPI fragments: each may carry `paths` and/or `components`
(and the head carries everything else). Keys are merged one level deep under
`paths` and per-section under `components`; a duplicate key is an error, so a
path or schema is defined exactly once across the parts.
"""
import glob
import sys

import yaml


def main() -> int:
    parts = sorted(glob.glob("openapi/parts/*.yaml"))
    out: dict = {}
    seen: dict[str, str] = {}
    for p in parts:
        with open(p) as f:
            doc = yaml.safe_load(f) or {}
        for k, v in doc.items():
            if k == "paths":
                out.setdefault("paths", {})
                for path, item in v.items():
                    key = f"paths.{path}"
                    if key in seen:
                        sys.exit(f"{p}: duplicate {key} (first in {seen[key]})")
                    seen[key] = p
                    out["paths"][path] = item
            elif k == "components":
                out.setdefault("components", {})
                for section, items in v.items():
                    out["components"].setdefault(section, {})
                    for name, item in items.items():
                        key = f"components.{section}.{name}"
                        if key in seen:
                            sys.exit(f"{p}: duplicate {key} (first in {seen[key]})")
                        seen[key] = p
                        out["components"][section][name] = item
            else:
                if k in out:
                    sys.exit(f"{p}: duplicate top-level {k}")
                out[k] = v
    order = ["openapi", "info", "servers", "tags", "x-tagGroups", "security", "paths", "components"]
    ordered = {k: out[k] for k in order if k in out}
    ordered.update({k: v for k, v in out.items() if k not in ordered})
    with open("openapi/openapi.yaml", "w") as f:
        f.write("# GENERATED by scripts/openapi_merge.py from openapi/parts/*.yaml — edit the parts.\n")
        yaml.safe_dump(ordered, f, sort_keys=False, allow_unicode=True, width=100)
    print(f"merged {len(parts)} parts: {len(out.get('paths', {}))} paths, "
          f"{sum(len(s) for s in out.get('components', {}).values())} components")
    return 0


if __name__ == "__main__":
    sys.exit(main())
