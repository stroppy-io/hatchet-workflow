// RenderDatabase renders a database's on-host config files into a render.Config
// (the same artifact the wizard previews and the agent writes — preview ==
// execution, B3). totalMemoryMB sizes percent-based defaults.
//
// Single-shape config for postgres / mysql / mariadb / picodata.
// TODO(render): HA shapes (patroni/etcd connect_address + etcd hosts bindings);
// ydb/cockroach use cluster configs/flags, not a single file (handled by their
// binary recipes), so they render no config here.
func RenderDatabase(db *domain.Database, totalMemoryMB int) (*renderpb.Config, error) {
	switch db.GetKind() {
	case domain.Database_KIND_POSTGRES:
		return renderPostgres(db, totalMemoryMB), nil
	case domain.Database_KIND_MYSQL, domain.Database_KIND_MARIADB:
		return renderMySQL(db, totalMemoryMB), nil
	case domain.Database_KIND_PICODATA:
		return renderPicodata(db, totalMemoryMB), nil
	case domain.Database_KIND_YDB, domain.Database_KIND_COCKROACH:
		return &renderpb.Config{Id: "no-file-config"}, nil // cluster config via the binary recipe
	default:
		return nil, fmt.Errorf("render: unsupported database kind %s", db.GetKind())
	}
}

func renderPostgres(db *domain.Database, totalMemoryMB int) *renderpb.Config {
	// Debian/Ubuntu pgdg packages keep per-version config under
	// /etc/postgresql/<version>/main — writing to a bare /main is ignored.
	version := db.GetVersion()
	if version == "" {
		version = "16"
	}
	dir := "/etc/postgresql/" + version + "/main/"
	return &renderpb.Config{
		Id: "postgres-config",
		Items: []*renderpb.Config_Item{
			// Tuning goes into conf.d/ (Debian's postgresql.conf has include_dir
			// 'conf.d') so the package's data_directory/hba_file stay intact;
			// pg_hba is a full file we own.
			fileItem("postgresql.conf", dir+"conf.d/stroppy.conf", renderPostgresConf(version, totalMemoryMB)),
			fileItem("pg_hba.conf", dir+"pg_hba.conf", postgresPgHbaConf),
		},
	}
}

// postgresDefaults is a minimal, deterministic default set. Percent values are
// resolved against the memory budget.
//
// TODO(render): recast the fuller per-version matrix from old domain/types.
func postgresDefaults() map[string]string {
	return map[string]string{
		"listen_addresses":     "'*'",
		"max_connections":      "200",
		"shared_buffers":       "25%",
		"effective_cache_size": "75%",
		"maintenance_work_mem": "5%",
		"work_mem":             "16MB",
		"wal_level":            "replica",
		"max_wal_senders":      "10",
	}
}

func renderPostgresConf(version string, totalMemoryMB int) string {
	_ = version // TODO(render): per-version tuning
	conf := postgresDefaults()
	resolveMemoryPercents(conf, totalMemoryMB)

	keys := make([]string, 0, len(conf))
	for k := range conf {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b strings.Builder
	b.WriteString("# Generated by stroppy\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "%s = %s\n", k, conf[k])
	}
	return b.String()
}

// ─── mysql / mariadb ──────────────────────────────────────────────────────────

func renderMySQL(_ *domain.Database, totalMemoryMB int) *renderpb.Config {
	return &renderpb.Config{
		Id:    "mysql-config",
		Items: []*renderpb.Config_Item{fileItem("my.cnf", "/etc/mysql/mysql.conf.d/zz-stroppy.cnf", renderMyCnf(totalMemoryMB))},
	}
}

func renderMyCnf(totalMemoryMB int) string {
	return formatMysqld(baseMysqld(), totalMemoryMB)
}

// baseMysqld is the common [mysqld] tuning shared by single and replicated nodes.
func baseMysqld() map[string]string {
	return map[string]string{
		"bind-address":                   "0.0.0.0",
		"max_connections":                "500",
		"innodb_buffer_pool_size":        "50%",
		"innodb_log_file_size":           "256MB",
		"innodb_flush_log_at_trx_commit": "1",
		"innodb_flush_method":            "O_DIRECT",
	}
}

// formatMysqld resolves percent-memory and renders a [mysqld] section.
func formatMysqld(conf map[string]string, totalMemoryMB int) string {
	resolveMemoryPercents(conf, totalMemoryMB)
	keys := make([]string, 0, len(conf))
	for k := range conf {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	b.WriteString("# Generated by stroppy\n[mysqld]\n")
	for _, k := range keys {
		// MySQL uses M/G suffixes; the percent resolver emits MB.
		v := strings.ReplaceAll(conf[k], "MB", "M")
		fmt.Fprintf(&b, "%s = %s\n", k, v)
	}
	return b.String()
}

// ─── picodata ───────────────────────────────────────────────────────────────

func renderPicodata(_ *domain.Database, totalMemoryMB int) *renderpb.Config {
	return &renderpb.Config{
		Id:    "picodata-config",
		Items: []*renderpb.Config_Item{fileItem("picodata.yaml", "/etc/picodata/picodata.yaml", renderPicodataYAML(totalMemoryMB))},
	}
}

func renderPicodataYAML(totalMemoryMB int) string {
	memMB := totalMemoryMB / 2
	if memMB < 256 {
		memMB = 256
	}
	var b strings.Builder
	b.WriteString("# Generated by stroppy\ninstance:\n")
	fmt.Fprintf(&b, "  memtx:\n    memory: %dM\n", memMB)
	b.WriteString("  iproto:\n    listen: 0.0.0.0:3301\n")
	b.WriteString("  pg:\n    listen: 0.0.0.0:5432\n")
	b.WriteString("  http:\n    listen: 0.0.0.0:8081\n")
	return b.String()
}

const postgresPgHbaConf = `# Generated by stroppy
local   all             all                 trust
host    all             all   127.0.0.1/32  trust
host    all             all   ::1/128       trust
host    all             all   0.0.0.0/0     trust
host    replication     all   0.0.0.0/0     trust
local   replication     all                 trust
`

// resolveMemoryPercents replaces "<N>%" values with "<MB>MB" sized against the
// memory budget, floored at 32 MB and capped at 2048 MB.
func resolveMemoryPercents(m map[string]string, totalMemoryMB int) {
	for k, v := range m {
		if !strings.HasSuffix(v, "%") {
			continue
		}
		pct, err := strconv.Atoi(strings.TrimSuffix(v, "%"))
		if err != nil {
			continue
		}
		mb := totalMemoryMB * pct / 100
		switch {
		case mb < 32:
			mb = 32
		case mb > 2048:
			mb = 2048
		}
		m[k] = strconv.Itoa(mb) + "MB"
	}
}

func fileItem(id, path, content string) *renderpb.Config_Item {
	return &renderpb.Config_Item{
		Id: id,
		Rendered: &renderpb.Config_Item_File{File: &system.File{
			Info: &system.File_Info{Path: path},
			Source: &system.File_Content_{Content: &system.File_Content{
				Content: &system.File_Content_Text{Text: content},
			}},
		}},
	}
}
