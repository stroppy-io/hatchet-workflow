package dbconfig

import (
	"fmt"
	"strings"
)

// ProxySQL backend host placeholder. The agent substitutes
// __PROXYSQL_BACKEND_HOST_<i>__ with the actual MySQL hostname before writing
// proxysql.cnf, so a single edited body works on every ProxySQL instance.
const proxysqlBackendPlaceholderPrefix = "__PROXYSQL_BACKEND_HOST_"

func proxysqlBackendPlaceholder(i int) string {
	return fmt.Sprintf("%s%d__", proxysqlBackendPlaceholderPrefix, i)
}

// RenderProxySQLConfOpts collects what RenderProxySQLConf needs.
type RenderProxySQLConfOpts struct {
	BackendCount    int // number of MySQL nodes — drives placeholder count
	BackendPort     int // backend MySQL port; defaults to 3306
	ListenPort      int // ProxySQL client interface; defaults to 6033
	AdminPort       int // ProxySQL admin interface; defaults to 6032
	WriterHostgroup int // hostgroup id for writes; defaults to 10
	ReaderHostgroup int // hostgroup id for reads;  defaults to 20
}

// RenderProxySQLConf returns the proxysql.cnf body the agent writes into
// /etc/proxysql.cnf. Backend hosts are emitted as
// __PROXYSQL_BACKEND_HOST_<i>__ placeholders the agent fills with real
// hostnames at run time. Index 0 is the writer (writer hostgroup);
// remaining backends are readers — same convention the inline writer used
// before this lift.
func RenderProxySQLConf(opts RenderProxySQLConfOpts) string {
	if opts.ListenPort == 0 {
		opts.ListenPort = 6033
	}
	if opts.AdminPort == 0 {
		opts.AdminPort = 6032
	}
	if opts.WriterHostgroup == 0 {
		opts.WriterHostgroup = 10
	}
	if opts.ReaderHostgroup == 0 {
		opts.ReaderHostgroup = 20
	}
	port := opts.BackendPort
	if port == 0 {
		port = 3306
	}

	var b strings.Builder
	b.WriteString("# Generated by stroppy-agent\n")
	b.WriteString("datadir=\"/var/lib/proxysql\"\n\n")

	b.WriteString("admin_variables=\n{\n")
	b.WriteString("    admin_credentials=\"admin:admin;radmin:radmin\"\n")
	fmt.Fprintf(&b, "    mysql_ifaces=\"0.0.0.0:%d\"\n", opts.AdminPort)
	b.WriteString("}\n\n")

	b.WriteString("mysql_variables=\n{\n")
	b.WriteString("    threads=4\n")
	b.WriteString("    max_connections=2048\n")
	b.WriteString("    default_query_delay=0\n")
	b.WriteString("    default_query_timeout=36000000\n")
	fmt.Fprintf(&b, "    interfaces=\"0.0.0.0:%d\"\n", opts.ListenPort)
	b.WriteString("    monitor_username=\"monitor\"\n")
	b.WriteString("    monitor_password=\"monitor\"\n")
	b.WriteString("}\n\n")

	b.WriteString("mysql_servers=\n(\n")
	for i := 0; i < opts.BackendCount; i++ {
		hostgroup := opts.WriterHostgroup
		if i > 0 {
			hostgroup = opts.ReaderHostgroup
		}
		fmt.Fprintf(&b, "    { address=\"%s\", port=%d, hostgroup=%d, max_connections=100 },\n",
			proxysqlBackendPlaceholder(i), port, hostgroup)
	}
	b.WriteString(")\n\n")

	b.WriteString("mysql_users=\n(\n")
	fmt.Fprintf(&b, "    { username=\"root\", password=\"\", default_hostgroup=%d, default_schema=\"mysql\", max_connections=1000, active=1 },\n", opts.WriterHostgroup)
	b.WriteString(")\n\n")

	b.WriteString("mysql_query_rules=\n(\n")
	fmt.Fprintf(&b, "    { rule_id=1, active=1, match_digest=\"^SELECT .* FOR UPDATE$\", destination_hostgroup=%d, apply=1 },\n", opts.WriterHostgroup)
	fmt.Fprintf(&b, "    { rule_id=2, active=1, match_digest=\"^SELECT\", destination_hostgroup=%d, apply=1 },\n", opts.ReaderHostgroup)
	b.WriteString(")\n")
	return b.String()
}

// SubstituteProxySQLBackends replaces __PROXYSQL_BACKEND_HOST_<i>__
// placeholders with the host portion of each entry in `backends`. Entries
// can be plain hosts or "host:port"; only the host part is substituted —
// the port is already a literal in the rendered body.
func SubstituteProxySQLBackends(body string, backends []string) string {
	for i, ba := range backends {
		host := ba
		if idx := strings.LastIndex(ba, ":"); idx > 0 {
			host = ba[:idx]
		}
		body = strings.ReplaceAll(body, proxysqlBackendPlaceholder(i), host)
	}
	return body
}
